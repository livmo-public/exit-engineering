"""Value check (Task 8): the workbook formulas, recalculated, equal the Python figures.

The sample company is generated by tools/make_sample.py. Its workbook is recalculated with the
formulas library; every key of the cell map is compared with metrics on the same canonical files.
"""
import json
from pathlib import Path

import pytest

import build_workbook
import canonical
import helpers
import make_sample
import metrics
import progress
import run_checks

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "skill" / "data"
TTM_MONTHS = ["2025-10", "2025-11", "2025-12"] + [f"2026-{m:02d}" for m in range(1, 10)]


def computed_titles():
    tabs = json.loads((DATA / "workbook.json").read_text(encoding="utf-8"))
    return [t["title"] for t in tabs if t["kind"] == "computed"]


def recalculated(sample_built, sample_recalc, key):
    sheet, cell = sample_built.cell_map[key]
    return helpers.cell_value(sample_recalc.values, sample_built.path, sheet, cell)


def test_formulas_equal_python(sample_built, sample_recalc):
    assert len(sample_built.cell_map) > 150
    assert set(sample_built.python_values) == set(sample_built.cell_map)
    for key, expected in sample_built.python_values.items():
        got = recalculated(sample_built, sample_recalc, key)
        assert got == pytest.approx(expected, abs=0.01), key


def test_no_error_values_in_computed_tabs(sample_recalc):
    assert helpers.error_cells(sample_recalc.values, computed_titles()) == []


def test_error_scan_reports_an_error(sample_recalc):
    # The scan must be able to fail: a planted error value in a computed tab is reported.
    from formulas.functions import XlError
    title = computed_titles()[0].upper()
    planted = f"'[X.XLSX]{title}'!A1"
    fake = {**sample_recalc.values, planted: XlError("#NAME?")}
    assert helpers.error_cells(fake, computed_titles()) == [planted]


def test_adjusted_ttm_equals_chat_summary(sample_built, sample_recalc):
    summary = build_workbook.chat_summary(sample_built.state, sample_built.dir, DATA)
    got = recalculated(sample_built, sample_recalc, "bridge.adjusted.TTM")
    assert got == pytest.approx(summary["adjusted_ebitda"]["TTM"], abs=0.01)


def test_rejected_adjustment_stays_out_of_adjusted_ebitda(sample_built, sample_recalc):
    adjustments = sample_built.state["adjustments"]
    assert {a["decision"] for a in adjustments} == {"approved", "edited", "rejected"}

    def total(decisions):
        return sum(metrics.adjustment_amount(a, TTM_MONTHS, "TTM")
                   for a in adjustments if a["decision"] in decisions)

    assert total(("approved", "edited")) > 0 and total(("rejected",)) > 0
    added = (recalculated(sample_built, sample_recalc, "bridge.adjusted.TTM")
             - recalculated(sample_built, sample_recalc, "bridge.ebitda.TTM"))
    assert added == pytest.approx(total(("approved", "edited")), abs=0.01)


def test_sample_has_planted_findings(sample_dir):
    state = progress.load(sample_dir / "progress.json")
    assert {"K01", "K08", "K12"} <= {f["check_id"] for f in state["findings"]}


def test_planted_findings_come_from_run_checks(sample_built):
    state = sample_built.state
    computed = [f for f in state["findings"] if f["method"] == "computed"]
    assert computed == run_checks.run(state, sample_built.dir, DATA)
    [owner] = [f for f in state["findings"] if f["method"] == "owner_question"]
    assert owner == run_checks.owner_findings(state, {"K12": make_sample.K12_STATEMENT}, DATA)[0]


def test_sample_shape(sample_built):
    read = lambda kind: canonical.read(kind, sample_built.dir / f"{kind}.csv")  # noqa: E731
    pl, bs, subs, vendor = read("pl"), read("bs"), read("subs"), read("vendor")
    months = sorted({r["period"] for r in pl})
    assert (months[0], months[-1], len(months)) == ("2024-07", "2026-09", 27)
    assert len({canonical.name_key(r["customer"]) for r in subs}) == 40
    assert {r["interval"] for r in subs} == {"month", "year"}
    assert any(r["account"] == "Suspense" and r["balance"] != 0 for r in bs)
    assert any(r["vendor"] == make_sample.RELATED_PARTY for r in vendor)
    assert not any(r["subtype"] == "deferred_revenue" for r in bs)
    assert sample_built.state["intake"]["fiscal_year_end_month"] == 12
    assert make_sample.COMPANY == "Sample SaaS Co."


def test_every_uploaded_file_with_a_canonical_kind_has_a_readable_path(sample_built):
    catalog = json.loads((DATA / "files.json").read_text(encoding="utf-8"))
    checked = 0
    for record in catalog:
        entry = sample_built.state["files"].get(record["id"], {})
        if entry.get("status") != "uploaded":
            continue
        if record["canonical_kind"]:
            canonical.read(record["canonical_kind"], Path(entry["canonical_path"]))
            checked += 1
        else:
            assert "canonical_path" not in entry, record["id"]
    assert checked == 9


def test_sample_is_deterministic_and_the_committed_copy_is_current(tmp_path, sample_dir):
    first = make_sample.make_sample(tmp_path / "a", seed=7)
    second = make_sample.make_sample(tmp_path / "b", seed=7)
    other = make_sample.make_sample(tmp_path / "c", seed=8)
    names = sorted(p.name for p in first.glob("*.csv"))
    assert names and names == sorted(p.name for p in sample_dir.glob("*.csv"))
    for name in names:
        assert (first / name).read_bytes() == (second / name).read_bytes(), name
        assert (first / name).read_bytes() == (sample_dir / name).read_bytes(), name
    assert (first / "sales.csv").read_bytes() != (other / "sales.csv").read_bytes()
    assert (sample_dir / make_sample.WORKBOOK_NAME).is_file()
    committed = progress.load(sample_dir / "progress.json")
    fresh = progress.load(first / "progress.json")
    for key in ("findings", "responses", "adjustments", "intake"):
        assert committed[key] == fresh[key], key
